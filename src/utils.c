int GetAng(const vec3i* vec1, const vec3i* vec2)
{
    int angle;
    int product;
    int mag;

    product = dot(vec1, vec2);
    mag = (GetMagnitude(vec1) * GetMagnitude(vec2)) >> FIXED_SHIFT;
    if (mag == 0)
        product = 4095;
    else
        product = (product / mag);

    if (product > 4095)
        product = 4095;
    else if (product < -4095)
        product = -4095;

    angle = arccos(product);

    return (angle);
}

int32 GetMagnitude(const vec3i* v)
{
    return rsqrt(v->x * v->x + v->y * v->y + v->z * v->z);
}

int32 GetMagnitudeSqr(const vec3i* v)
{
    return v->x * v->x + v->y * v->y + v->z * v->z;
}

int32 GetMagnitudeApprox(int32 dx, int32 dy)
{
    dx = abs(dx);
    dy = abs(dy);
    return (dx > dy) ? (dx + (dy >> 1)) : (dy + (dx >> 1));
}

int dot(const vec3i* vec1, const vec3i* vec2)
{
    return vec1->x * vec2->x + vec1->y * vec2->y + vec1->z * vec2->z;
}

int arccos(int value)
{
    int angle;
    int new_val;

    if (value < 0)
        new_val = -value;
    else
        new_val = value;
    angle = (int)arccos_tab[new_val];
    if (value < 0)
        angle = 8192 + (8192 - angle);
    return (angle);
}

int ang(int a)
{
    a = a & 4095;

    if (a > 2048)
    {
        return (a - 4096);
    }

    return a; // -2047..2048
}

int32 ratan2(int32 y, int32 x)
{
    int32 o = 0;

    if (x == 0 && y == 0)
        return 0;

    if (x < 0) {
        o += 4;
        x = -x;
    }

    if (y < 0) {
        o += 2;
        y = -y;
    }

    if (y > x) {
        int32 t = x;
        x = y;
        y = t;
        o++;
    }

    return abs(atanTable[(y << 11) / x] + atanOctant[o]) << 16 >> 20;
}

uint32 rsqrt(uint32 x)
{
    uint32 m = 0x40000000;
    uint32 y = 0;
    uint32 z = 0;

    do {
        y += m;

        if (y > x) {
            y = z;
        } else {
            x -= y;
            y = z + m;
        }

        z = y >> 1;
    } while (m >>= 2);

    return y;
}

uint32 speedColor(int32 angle)
{
    int32 b;
    b = (rsin(angle) >> 5) + 128 + 64;
    if (b > 255)
        b = 255;
    return (b << 16);
}

uint32 weaponColor(int32 angle)
{
    int32 r, g, b;

    rsincos(angle, r, g);
    b = -r;
    r = (r >> 5) + 128;
    g = (g >> 5) + 128;
    b = (b >> 5) + 128;

    if (r > 255)
        r = 255;
    if (g > 255)
        g = 255;
    if (b > 255)
        b = 255;

    return r | (g << 8) | (b << 16);
}

